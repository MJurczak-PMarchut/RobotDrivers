/*
 * StrategyGlyphs.hpp
 *
 * One glyph per strategy for the bottom-right statistics box ("Strat", StatsBox[2]) of the
 * DEBUG_SCREEN display, so the running algorithm can be read off the screen at a glance: the
 * short name in large characters and the family below. Drawn by boundingBox::draw_glyph()
 * (RobotHardware.hpp) after calibration.
 *
 * Format of every glyph (as Adafruit GFX drawBitmap() expects, also epd_bitmap_Untitled):
 * kGlyphWidth x kGlyphHeight pixels, rows top to bottom, kGlyphRowBytes bytes per row, the most
 * significant bit of a byte is the leftmost pixel, 1 = lit. These were drawn from a 5x7 pixel
 * font: the label scaled x4, the family name x1, both centred.
 */

